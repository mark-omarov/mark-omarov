const glyph = (ch: string) => G[ch] ?? G['?']!;

/** Width of a string in pixels, with a pixel between letters. */
export function measure(s: string, bold = false) {
  let w = 0;
  for (const ch of s) w += glyph(ch)[0]!.length + 1 + (bold ? 1 : 0);
  return Math.max(0, w - 1);
}

/** Draws text with its cap line at y; returns the width drawn. */
export function text(
  f: Frame,
  s: string,
  x: number,
  y: number,
  c: RGB,
  bold = false
) {
  let cx = Math.round(x);
  for (const ch of s) {
    const g = glyph(ch);
    for (let ry = 0; ry < g.length; ry++)
      for (let rx = 0; rx < g[ry]!.length; rx++)
        if (g[ry]![rx] === '#') {
          f.set(cx + rx, y + ry, c);
          if (bold) f.set(cx + rx + 1, y + ry, c);
        }
    cx += g[0]!.length + 1 + (bold ? 1 : 0);
  }
  return cx - Math.round(x) - 1;
}

/** Text centred on cx. */
export function centred(
  f: Frame,
  s: string,
  cx: number,
  y: number,
  c: RGB,
  bold = false
) {
  text(f, s, cx - Math.floor(measure(s, bold) / 2), y, c, bold);
}

/** Breaks a string into lines no wider than max, at spaces. */
export function wrap(s: string, max: number, bold = false) {
  const lines: string[] = [];
  let line = '';
  for (const word of s.split(' ')) {
    const next = line ? `${line} ${word}` : word;
    if (line && measure(next, bold) > max) {
      lines.push(line);
      line = word;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
